// Движок не знает ни о DOM, ни о localStorage. Всё, что ему нужно извне,
// приходит аргументами: состояние, набор правил и генератор случайных чисел.

export const clamp = (v, lo, hi) => Math.min(hi, Math.max(lo, v));
export const r1 = v => Math.round(v * 10) / 10;

// Бросок кубика dN через переданный генератор [0, 1).
// Вынесено отдельно, чтобы тесты и симулятор могли подставить сидированный генератор
// и получить воспроизводимые броски.
export const rollDie = (rng, n) => Math.floor(rng() * n) + 1;

// Генератор с зерном (mulberry32). Один и тот же seed → одна и та же последовательность.
// Используется в тестах, симуляциях и будущей самоигре ИИ.
export function mulberry32(seed){
  let a = seed >>> 0;
  return function(){
    a = (a + 0x6D2B79F5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
